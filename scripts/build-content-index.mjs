import { readdir, readFile, unlink, writeFile, mkdir } from 'node:fs/promises';
import { basename, extname, join } from 'node:path';
import sharp from 'sharp';

const root = process.cwd();
const imageExtensions = new Set(['.avif', '.gif', '.jpeg', '.jpg', '.png', '.webp']);

const listImages = async directory => {
  const files = await readdir(join(root, directory), { withFileTypes: true });
  return files
    .filter(file => file.isFile() && imageExtensions.has(extname(file.name).toLowerCase()))
    .map(file => ({
      source: `${directory}/${file.name}`,
      name: file.name,
      key: basename(file.name, extname(file.name))
    }))
    .sort((left, right) => left.name.localeCompare(right.name));
};

const optimizeImages = async (images, kind) => {
  const outputDirectory = `assets/optimized/${kind}`;
  const outputPath = join(root, outputDirectory);
  await mkdir(outputPath, { recursive: true });
  const expectedFiles = new Set(images.map(image => `${image.name}.webp`));
  const existingFiles = await readdir(outputPath, { withFileTypes: true });
  await Promise.all(existingFiles
    .filter(file => file.isFile() && !expectedFiles.has(file.name))
    .map(file => unlink(join(outputPath, file.name))));

  return Promise.all(images.map(async image => {
    const output = `${outputDirectory}/${image.name}.webp`;
    const width = kind === 'photos' ? 1200 : 800;
    await sharp(join(root, image.source), { animated: false })
      .rotate()
      .resize({ width, withoutEnlargement: true })
      .webp({ quality: 80, effort: 4 })
      .toFile(join(root, output));
    return { ...image, output };
  }));
};

const titleFromFilename = file => basename(file, extname(file))
  .replace(/[-_]+/g, ' ')
  .replace(/\b\w/g, letter => letter.toUpperCase());

const sourcePhotos = await listImages('assets/photos');
const sourceProjects = await listImages('assets/projects');
const photos = (await optimizeImages(sourcePhotos, 'photos')).map(photo => ({
  src: photo.output,
  alt: 'Durvankur'
}));
const optimizedProjects = await optimizeImages(sourceProjects, 'projects');
const projects = [];
for (const project of optimizedProjects) {
  const metadataPath = join(root, 'assets/projects', `${project.key}.json`);
  let metadata = {};
  try { metadata = JSON.parse(await readFile(metadataPath, 'utf8')); } catch {}
  projects.push({
    image: project.output,
    title: metadata.title || titleFromFilename(project.name),
    description: metadata.description || '',
    tags: Array.isArray(metadata.tags) ? metadata.tags : [],
    link: metadata.link || '#'
  });
}

const content = { photos, projects };
await writeFile(
  join(root, 'assets/content.js'),
  '/* Generated by npm run build. Do not edit manually. */\nwindow.PORTFOLIO_CONTENT = ' + JSON.stringify(content, null, 2) + ';\n'
);
console.log(`Optimized and indexed ${content.photos.length} photo(s) and ${content.projects.length} project(s).`);
