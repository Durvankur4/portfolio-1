import { readdir, readFile, writeFile } from 'node:fs/promises';
import { basename, extname, join } from 'node:path';

const root = process.cwd();
const imageExtensions = new Set(['.avif', '.gif', '.jpeg', '.jpg', '.png', '.webp']);
const listImages = async directory => {
  const files = await readdir(join(root, directory), { withFileTypes: true });
  return files
    .filter(file => file.isFile() && imageExtensions.has(extname(file.name).toLowerCase()))
    .map(file => directory + '/' + file.name)
    .sort((left, right) => left.localeCompare(right));
};
const titleFromFilename = file => basename(file, extname(file)).replace(/[-_]+/g, ' ').replace(/\b\w/g, letter => letter.toUpperCase());
const photos = (await listImages('assets/photos')).map(src => ({ src, alt: 'Durvankur' }));
const projects = [];
for (const image of await listImages('assets/projects')) {
  const metadataPath = join(root, 'assets/projects', basename(image, extname(image)) + '.json');
  let metadata = {};
  try { metadata = JSON.parse(await readFile(metadataPath, 'utf8')); } catch {}
  projects.push({ image, title: metadata.title || titleFromFilename(image), description: metadata.description || '', tags: Array.isArray(metadata.tags) ? metadata.tags : [], link: metadata.link || '#' });
}
const content = { photos, projects };
await writeFile(join(root, 'assets/content.js'), '/* Generated by npm run build. Do not edit manually. */\nwindow.PORTFOLIO_CONTENT = ' + JSON.stringify(content, null, 2) + ';\n');
console.log('Indexed ' + content.photos.length + ' photo(s) and ' + content.projects.length + ' project(s).');
